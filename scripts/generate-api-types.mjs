import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import {
  assertOpenApiDocument,
  buildOpenApiHeaders,
  resolveOpenApiUrl,
} from './openapi-contract.mjs';

const defaultOutput = resolve('src/shared/api/schema.d.ts');

function getOptions(argv) {
  const check = argv.includes('--check');
  const outputArg = argv.find((value) => value.startsWith('--output='));
  const output = outputArg
    ? resolve(outputArg.slice('--output='.length))
    : defaultOutput;

  return { check, output };
}

async function fetchOpenApiDocument() {
  const response = await fetch(resolveOpenApiUrl(), {
    headers: buildOpenApiHeaders(),
  });

  if (!response.ok) {
    throw new Error(`OpenAPI fetch failed with HTTP ${response.status}.`);
  }

  let document;
  try {
    document = JSON.parse(await response.text());
  } catch {
    throw new Error('OpenAPI endpoint returned invalid JSON.');
  }

  return assertOpenApiDocument(document);
}

async function renderTypes(document) {
  const generated = await openapiTS(document, { alphabetize: true });
  const source =
    typeof generated === 'string' ? generated : astToString(generated);

  return `/**\n * Generated from the authenticated OpenAPI contract.\n * Do not edit this file by hand. Run pnpm run api:types.\n */\n\n${source.trim()}\n`;
}

async function generate(output) {
  const document = await fetchOpenApiDocument();
  const source = await renderTypes(document);
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, source, 'utf8');
}

async function check(output) {
  const directory = await mkdtemp(resolve(tmpdir(), 'autodrive-openapi-'));
  const generatedOutput = resolve(directory, 'schema.d.ts');

  try {
    await generate(generatedOutput);
    const [expected, actual] = await Promise.all([
      readFile(output, 'utf8').catch(() => null),
      readFile(generatedOutput, 'utf8'),
    ]);

    if (expected !== actual) {
      throw new Error(
        `Generated API types are stale. Run pnpm run api:types and commit ${output}.`,
      );
    }
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}

const { check: shouldCheck, output } = getOptions(process.argv.slice(2));
if (shouldCheck) {
  await check(output);
  console.log(`OpenAPI types are up to date: ${output}`);
} else {
  await generate(output);
  console.log(`Generated OpenAPI types: ${output}`);
}
